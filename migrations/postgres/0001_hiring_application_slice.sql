CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'staff',
    system TEXT NOT NULL DEFAULT 'distribution',
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE UNIQUE INDEX idx_users_system_username ON users(username, system);

CREATE TABLE hiring_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    location TEXT,
    employment_type TEXT NOT NULL DEFAULT 'Full-time',
    description TEXT,
    status TEXT NOT NULL DEFAULT 'draft',
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE INDEX idx_hiring_jobs_status ON hiring_jobs(status);

CREATE TABLE hiring_candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    position TEXT NOT NULL,
    source TEXT,
    status TEXT NOT NULL DEFAULT 'new',
    rating INTEGER,
    resume_url TEXT,
    notes TEXT,
    job_id BIGINT REFERENCES hiring_jobs(id),
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE INDEX idx_hiring_candidates_status ON hiring_candidates(status);
CREATE INDEX idx_hiring_candidates_position ON hiring_candidates(position);
CREATE INDEX idx_hiring_candidates_job ON hiring_candidates(job_id);
