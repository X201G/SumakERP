CREATE TABLE delivery_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    vehicle TEXT,
    route_date DATE NOT NULL,
    driver_id BIGINT NOT NULL REFERENCES users(id),
    status TEXT NOT NULL DEFAULT 'assigned',
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE INDEX idx_delivery_routes_driver_date
    ON delivery_routes(driver_id, route_date);

CREATE TABLE delivery_route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL REFERENCES delivery_routes(id) ON DELETE CASCADE,
    stop_order INTEGER NOT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT,
    address TEXT,
    maps_url TEXT,
    UNIQUE (route_id, stop_order)
);

CREATE INDEX idx_delivery_route_stops_route
    ON delivery_route_stops(route_id, stop_order);

CREATE TABLE delivery_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    route_id BIGINT NOT NULL REFERENCES delivery_routes(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    read_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_delivery_notifications_user_read
    ON delivery_notifications(user_id, read_at);

CREATE TABLE delivery_push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP WITHOUT TIME ZONE
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE INDEX idx_delivery_push_subscriptions_user
    ON delivery_push_subscriptions(user_id);
