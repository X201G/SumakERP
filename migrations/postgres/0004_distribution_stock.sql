CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE subcategories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES categories(id),
    subcategory_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hsn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hsn_code TEXT NOT NULL UNIQUE,
    description TEXT,
    gst_rate DOUBLE PRECISION DEFAULT 18.0,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    email TEXT,
    address TEXT,
    city TEXT,
    state TEXT,
    gst_number TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name TEXT NOT NULL,
    print_description TEXT,
    category_id BIGINT REFERENCES categories(id),
    subcategory_id BIGINT REFERENCES subcategories(id),
    unit_id BIGINT REFERENCES units(id),
    hsn_id BIGINT REFERENCES hsn(id),
    tax_rate DOUBLE PRECISION DEFAULT 18.0,
    supplier_id BIGINT REFERENCES suppliers(id),
    sale_price DOUBLE PRECISION DEFAULT 0,
    sale_discount DOUBLE PRECISION DEFAULT 0,
    purchase_price DOUBLE PRECISION DEFAULT 0,
    purchase_discount DOUBLE PRECISION DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    movement_type TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    source_type TEXT,
    source_id BIGINT,
    source_no TEXT,
    movement_date DATE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    rate DOUBLE PRECISION DEFAULT 0,
    amount DOUBLE PRECISION DEFAULT 0
);

CREATE INDEX idx_stock_movements_product_date_id
    ON stock_movements (product_id, movement_date, id);
CREATE INDEX idx_stock_movements_product_source_date
    ON stock_movements (product_id, source_type, movement_date);
