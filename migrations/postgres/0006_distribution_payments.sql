CREATE TABLE sales_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT REFERENCES sales_invoices(id),
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    payment_date DATE NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    payment_mode TEXT DEFAULT 'cash',
    reference_no TEXT,
    remarks TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE purchase_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT REFERENCES purchase_invoices(id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    payment_date DATE NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    payment_mode TEXT DEFAULT 'cash',
    reference_no TEXT,
    remarks TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sales_payments_customer_date
    ON sales_payments (customer_id, payment_date, id);
CREATE INDEX idx_sales_payments_payment_date
    ON sales_payments (payment_date, id);
CREATE INDEX idx_sales_payments_invoice
    ON sales_payments (invoice_id);
CREATE INDEX idx_purchase_payments_supplier_date
    ON purchase_payments (supplier_id, payment_date, id);
CREATE INDEX idx_purchase_payments_payment_date
    ON purchase_payments (payment_date, id);
CREATE INDEX idx_purchase_payments_invoice
    ON purchase_payments (invoice_id);
